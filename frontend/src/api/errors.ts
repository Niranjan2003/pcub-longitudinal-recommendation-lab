import type { ZodError } from 'zod';

/**
 * Four ways a request can fail, deliberately kept apart because they imply
 * different things about whether a command may have been committed:
 *
 * - backend:   the backend answered with a JSON error body. Commands are atomic,
 *              so nothing was committed (the key is retired).
 * - network:   a GET could not reach the backend.
 * - uncertain: a POST got no usable answer (connection lost, proxy 502/504,
 *              non-JSON body, page reload). The command MAY have committed.
 * - contract:  the backend answered 2xx but the body did not match our schema.
 *              The command DID commit; we must not render partial data.
 */
export type ApiErrorKind = 'backend' | 'network' | 'uncertain' | 'contract';

export interface ApiErrorInit {
  kind: ApiErrorKind;
  message: string;
  status?: number;
  code?: string;
  /** Optional operator explanation the backend sometimes includes. Rendered verbatim. */
  action?: string;
  raw?: unknown;
  issues?: ZodError['issues'];
}

export class ApiError extends Error {
  readonly kind: ApiErrorKind;
  readonly status: number | undefined;
  readonly code: string | undefined;
  readonly action: string | undefined;
  readonly raw: unknown;
  readonly issues: ZodError['issues'] | undefined;

  constructor(init: ApiErrorInit) {
    super(init.message);
    this.name = 'ApiError';
    this.kind = init.kind;
    this.status = init.status;
    this.code = init.code;
    this.action = init.action;
    this.raw = init.raw;
    this.issues = init.issues;
  }
}

export function isApiError(e: unknown): e is ApiError {
  return e instanceof ApiError;
}

